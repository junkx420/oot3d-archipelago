#pragma once

// Game-thread side of the Archipelago integration (Phase 2).
//
// Owns the network client, the location table and the per-save sidecar.
// The check observer's events arrive through OnCheck and Update runs once
// per frame, both on the guest thread. The F1 panel may draw on another
// thread, so every public function locks, and the panel gets copies.

#include "ap_check_observer.h"
#include "ap_location_table.h"
#include "ap_network_client.h"
#include "ap_sidecar.h"

#include <cstdint>
#include <deque>
#include <filesystem>
#include <memory>
#include <mutex>
#include <optional>
#include <set>
#include <string>
#include <vector>

namespace Oot3dArchipelago {

inline constexpr std::uint32_t kSaveFileNum = kSaveContext + 0x14DCU;
inline constexpr std::uint32_t kSaveNewf = kSaveContext + 0x0030U; // "ZELDAZ"

class Session final {
public:
  struct Paths {
    std::filesystem::path SettingsFile;   // server, slot and uuid; no password
    std::filesystem::path SidecarDirectory;
    std::filesystem::path LocationTable;  // generated by the apworld phase
  };
  explicit Session(Paths paths);
  ~Session();

  void OnCheck(const CheckEvent &event);
  void Update(oot3d::recomp::a32::MemoryBus &memory);

  [[nodiscard]] ConnectionSettings Settings() const;
  void Connect(const ConnectionSettings &settings);
  void Disconnect();
  void Say(std::string text);
  [[nodiscard]] ConnectionState State() const;
  [[nodiscard]] std::vector<std::string> Console() const;

  struct Counters {
    std::size_t LocationTableSize = 0;
    std::size_t ChecksReported = 0;
    std::size_t ChecksUnmapped = 0;
    std::size_t ItemsFromServer = 0;
    std::int64_t ItemsApplied = 0;
    int SaveSlot = -1;
  };
  [[nodiscard]] Counters Stats() const;

private:
  void Log(std::string line);
  void LoadSettings();
  void SaveSettings() const;
  void HandleEvent(const NetworkEventVariant &event);
  void OpenSidecarIfReady(oot3d::recomp::a32::MemoryBus &memory);
  void Persist();
  void ReportLocation(std::int64_t id);

  mutable std::mutex mMutex;
  Paths mPaths;
  ConnectionSettings mSettings;
  std::string mUuid;
  std::unique_ptr<NetworkClient> mClient;
  std::optional<LocationTable> mLocations;
  std::deque<std::string> mConsole;

  // From SlotConnected.
  std::optional<SidecarIdentity> mSlot;
  std::set<std::int64_t> mServerChecked;
  std::vector<ReceivedItem> mServerItems;
  // Checks seen before a slot and save were known; sent once both are.
  std::vector<std::int64_t> mUnsentChecks;
  std::optional<SidecarState> mSidecar;
  std::size_t mUnmapped = 0;
};

} // namespace Oot3dArchipelago
