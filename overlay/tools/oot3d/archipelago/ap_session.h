#pragma once

// Game-thread side of the Archipelago integration (Phases 2 and 4).
//
// Owns the network client, the location and item tables and the per-save
// sidecar. The check observer's events arrive through OnCheck and its
// get-item overrides through OverrideGetItem; Update runs once per frame and
// gives received items. All of these run on the guest thread. The F1 panel may draw on another
// thread, so every public function locks, and the panel gets copies.

#include "ap_cheats.h"
#include "ap_check_observer.h"
#include "ap_cutscene_skip.h"
#include "ap_fairy_rewards.h"
#include "ap_item_receiver.h"
#include "ap_item_table.h"
#include "ap_location_table.h"
#include "ap_messages.h"
#include "ap_network_client.h"
#include "ap_save_sync.h"
#include "ap_sidecar.h"
#include "ap_song_replays.h"
#include "ap_world_state.h"

#include <array>
#include <chrono>
#include <cstdint>
#include <deque>
#include <filesystem>
#include <map>
#include <memory>
#include <mutex>
#include <optional>
#include <set>
#include <string>
#include <vector>

namespace Oot3dArchipelago {

inline constexpr std::uint32_t kSaveFileNum = kSaveContext + 0x14DCU;
inline constexpr std::uint32_t kSaveNewf = kSaveContext + 0x0030U; // "ZELDAZ"

// Whether the module runs, read once at startup: TRIAEVUM_ARCHIPELAGO=1 or 0
// when set, otherwise "enabled" in the settings file (off by default).
bool EnabledInSettings(const std::filesystem::path &settingsFile);
// Writes "enabled", keeping the file's other keys; takes effect at the next
// start, since the check observer's hooks are installed with the game.
bool SetEnabledInSettings(const std::filesystem::path &settingsFile, bool enabled);

// Client options kept in the settings file.
struct ClientOptions {
  bool AutoConnect = true;   // connect at startup with the saved server and slot
  bool Notifications = true; // in-game messages (items, DeathLink, goal)
  bool RememberPassword = false; // the password is saved, in plain text
  QuickTextMode QuickText = QuickTextMode::Off;
  bool FastChests = false; // every chest opens with the short animation
  SongReplayMode SongReplays = SongReplayMode::Off;
  DamageMultiplier Damage = DamageMultiplier::Normal;
  CheatOptions Cheats;
};

// One in-game message for the overlay.
struct Notification {
  enum class Kind : std::uint8_t { Info, ItemReceived, ItemSent, Death, Goal, Warning };
  Kind Type = Kind::Info;
  std::string Text;
  std::chrono::steady_clock::time_point Time;
};
inline constexpr auto kNotificationLifetime = std::chrono::seconds(6);
inline constexpr std::size_t kMaximumNotifications = 5;
// How long a placeholder's text stays ready after its last offer: the
// get-item's text box opens a little after the item is taken.
inline constexpr int kPlaceholderTextFrames = 300;

class Session final {
public:
  struct Paths {
    std::filesystem::path SettingsFile;   // server, slot and uuid; no password
    std::filesystem::path SidecarDirectory;
    std::filesystem::path LocationTable;  // generated by the apworld phase
    std::filesystem::path ItemTable;      // generated beside it
  };
  explicit Session(Paths paths);
  ~Session();

  void OnCheck(const CheckEvent &event);
  // What the location of an offer gives instead of its own item, once a
  // save of a connected slot is open; nothing (the game's own item) before.
  std::optional<std::uint16_t> OverrideGetItem(const LocationKey &key,
                                               oot3d::recomp::a32::MemoryBus &memory);
  // What a direct give (no offer) of a location gives instead of the game's
  // own item; nothing to keep the game's.
  std::optional<std::uint8_t> ReplaceDirectGive(const LocationKey &key, oot3d::recomp::a32::MemoryBus &memory);
  // The text entry to show instead of a looked-up one (CheckObserver::
  // SetMessageOverride): the recovery heart's text after a location offered
  // a placeholder says what the location held.
  std::optional<std::uint32_t> MessageEntry(std::uint32_t textId, std::uint32_t entry, std::uint32_t textBase,
                                            const std::optional<LocationKey> &offer,
                                            oot3d::recomp::a32::MemoryBus &memory);
  // The client is giving a received item (its Item_Give is no location).
  [[nodiscard]] bool Receiving() const;
  // The seed opens the forest exit and a save of the slot is open.
  [[nodiscard]] bool ForestExitOpen() const;
  // A save of the connected seed is open.
  [[nodiscard]] bool SeedActive() const;
  // Whether a location of the seed was taken (reported from this save, or
  // checked on the server); nothing without a seed or for a key that is not
  // one of its locations.
  [[nodiscard]] std::optional<bool> LocationTaken(const LocationKey &key) const;
  // A cow's location is part of the seed and not yet reported.
  [[nodiscard]] bool CowGivesItem(const LocationKey &key) const;
  // What a shop slot sells (ap_shops.h), and the slot was bought.
  CheckObserver::ShopSlotState ShopSlot(const LocationKey &key, oot3d::recomp::a32::MemoryBus &memory);
  void ShopBought(const LocationKey &key);
  void SetGuestRegionMapper(GuestRegionMapper mapper);
  // The check observer saw Link die without a fairy.
  void OnDeath();
  // The check observer saw a blue warp leave a scene: with cutscene
  // skips on and a connected save, skips the dungeon's cutscene and reports
  // its reward location.
  void OnBlueWarp(std::uint32_t pc, std::uint8_t scene, oot3d::recomp::a32::MemoryBus &memory);
  void Update(oot3d::recomp::a32::MemoryBus &memory);

  [[nodiscard]] ConnectionSettings Settings() const;
  [[nodiscard]] const std::filesystem::path &SettingsFile() const noexcept { return mPaths.SettingsFile; }
  // Client settings, kept in the settings file; they apply with or without
  // a connection.
  [[nodiscard]] CutsceneSkipOptions Skips() const;
  void SetSkips(const CutsceneSkipOptions &skips);
  [[nodiscard]] ClientOptions Options() const;
  void SetOptions(const ClientOptions &options);
  // Called with the options now and on every change (the window passes the
  // quick text mode to the check observer).
  void SetOptionsSink(std::function<void(const ClientOptions &)> sink);
  // Messages younger than kNotificationLifetime, oldest first; empty while
  // notifications are off.
  [[nodiscard]] std::vector<Notification> Notifications(
      std::chrono::steady_clock::time_point now = std::chrono::steady_clock::now()) const;
  void Connect(const ConnectionSettings &settings);
  void Disconnect();
  void Say(std::string text);
  [[nodiscard]] ConnectionState State() const;
  [[nodiscard]] std::vector<std::string> Console() const;

  struct Counters {
    std::size_t LocationTableSize = 0;
    std::size_t ChecksReported = 0;
    std::size_t ChecksUnmapped = 0;
    std::size_t ItemsFromServer = 0;
    std::int64_t ItemsApplied = 0;
    std::size_t LocationsScouted = 0;
    bool DeathLink = false;
    bool GoalReached = false;
    int SaveSlot = -1;
    // Title or file selection (SaveContext.game_mode not 0), from the last
    // Update.
    bool Frontend = false;
  };
  [[nodiscard]] Counters Stats() const;

private:
  void Log(std::string line);
  void Notify(Notification::Kind kind, std::string text);
  void NotifyReceived(const ReceivedItem &item, const std::string &name);
  void LoadSettings();
  void SaveSettings() const;
  void HandleEvent(const NetworkEventVariant &event);
  void OpenSidecarIfReady(oot3d::recomp::a32::MemoryBus &memory);
  void Persist();
  void FlushPersist();
  void ReportLocation(std::int64_t id);
  void GiveReceivedItems(oot3d::recomp::a32::MemoryBus &memory);
  void SyncProgress(oot3d::recomp::a32::MemoryBus &memory);
  void WatchGameSave();
  [[nodiscard]] std::filesystem::path GameSavePath(int saveSlot) const;
  void ApplyDeathLink(oot3d::recomp::a32::MemoryBus &memory);
  void WatchGoal(oot3d::recomp::a32::MemoryBus &memory);
  void WatchFairyFountain(oot3d::recomp::a32::MemoryBus &memory);
  void WatchTokens(oot3d::recomp::a32::MemoryBus &memory);
  void WatchTriforce();
  [[nodiscard]] std::string ItemName(std::int64_t item) const;
  void PreparePlaceholderText(std::int64_t location, const Placement &placement, bool foreign);

  mutable std::mutex mMutex;
  Paths mPaths;
  ConnectionSettings mSettings;
  CutsceneSkipOptions mSkips;
  ClientOptions mOptions;
  std::function<void(const ClientOptions &)> mOptionsSink;
  mutable std::deque<Notification> mNotifications;
  // The slot was connected in this session (for "connection lost").
  bool mWasConnected = false;
  // Names of what this slot's locations hold, from the scouts (owner's game).
  std::map<std::int64_t, std::pair<std::string, std::string>> mPlacementNames;
  int mSkipsLoggedForSlot = -1;
  CheatApplier mCheats;
  bool mCheatsDisabledLogged = false;
  std::string mUuid;
  std::unique_ptr<NetworkClient> mClient;
  std::optional<LocationTable> mLocations;
  std::optional<ItemTable> mItems;
  ItemReceiver mReceiver{GuestRegionMapper{}};
  bool mReceiverReported = false;
  // Locations whose offer showed this world's item itself in this session.
  std::set<std::int64_t> mShownAtLocation;
  // The text for the placeholder the last offer showed, for as many more
  // frames (the offer repeats every frame until it is taken).
  std::string mPlaceholderText;
  int mPlaceholderTextFrames = 0;
  // Each placeholder location's text, for the one Link takes from.
  std::map<std::int64_t, std::string> mPlaceholderTexts;
  // DeathLink (slot_data death_link): a received death waits until Link
  // can die; the game over it causes is not sent back for a while.
  bool mDeathLink = false;
  bool mKillPending = false;
  int mLinkDeathFrames = 0;
  // Goal: Link leaves Ganon's battle alive.
  std::uint16_t mPreviousScene = 0xFFFFU;
  bool mDiedInScene = false;
  std::deque<std::string> mConsole;
  bool mFrontend = false;
  bool mPersistPending = false;
  // ap_save_sync.h: the save synced since the last file selection, and the
  // game save file's last write time.
  std::optional<SidecarIdentity> mSyncedIdentity;
  int mSaveCheckCountdown = 0;
  std::optional<std::filesystem::file_time_type> mSaveStamp;
  int mSaveStampSlot = -1;
  SidecarWriter mWriter{mPaths.SidecarDirectory};

  // From SlotConnected.
  std::optional<SidecarIdentity> mSlot;
  WorldState mWorld;
  int mWorldLoggedForSlot = -1;
  // The upgrade fountain's rewards in the save on the previous frame.
  std::optional<FairyUpgrades> mFairyBaseline;
  // slot_data shop_prices by location id.
  std::map<std::int64_t, int> mShopPrices;
  // Triforce hunt (slot_data): pieces required, 0 when off; pieces counted.
  int mTriforceRequired = 0;
  int mTriforcePieces = 0;
  // Set when the placements are scouted; the save's gsFlags last seen.
  bool mTokensShuffled = false;
  std::size_t mTokenPlacementCount = 0;
  std::optional<std::array<std::uint8_t, kSaveGsFlagCount>> mTokenFlags;
  std::set<std::int64_t> mServerChecked;
  std::vector<ReceivedItem> mServerItems;
  std::map<std::int64_t, Placement> mPlacements;
  // Checks seen before a slot and save were known; sent once both are.
  std::vector<std::int64_t> mUnsentChecks;
  std::optional<SidecarState> mSidecar;
  std::size_t mUnmapped = 0;
};

} // namespace Oot3dArchipelago
